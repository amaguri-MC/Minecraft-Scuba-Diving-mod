package net.scubadive.client.creature.bottom;

import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.scubadive.ScubaDive;

/** Anemone shrimp: glassy pale body with white and purple spots, curled abdomen, long antennae. Texture generated by tools/F3_tex.py. */
@SuppressWarnings("unused")
public class AnemoneShrimpModel extends EntityModel<BottomRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(ScubaDive.id("anemone_shrimp"), "main");

	private final ModelPart thorax;
	private final ModelPart head;
	private final ModelPart abdomen1;
	private final ModelPart abdomen2;
	private final ModelPart fan;
	private final ModelPart antL;
	private final ModelPart antR;
	private final ModelPart legL;
	private final ModelPart legR;
	private final ModelPart clawL;
	private final ModelPart clawR;

	public AnemoneShrimpModel(ModelPart root) {
		super(root);
		this.thorax = root.getChild("thorax");
		this.head = this.thorax.getChild("head");
		this.abdomen1 = this.thorax.getChild("abdomen1");
		this.abdomen2 = this.abdomen1.getChild("abdomen2");
		this.fan = this.abdomen2.getChild("fan");
		this.antL = this.head.getChild("antL");
		this.antR = this.head.getChild("antR");
		this.legL = this.thorax.getChild("legL");
		this.legR = this.thorax.getChild("legR");
		this.clawL = this.head.getChild("clawL");
		this.clawR = this.head.getChild("clawR");
	}

	public static LayerDefinition createBodyLayer() {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
		PartDefinition thorax = root.addOrReplaceChild("thorax", CubeListBuilder.create()
				.texOffs(0, 0).addBox(-2f, -2f, -3f, 4f, 4f, 5f), PartPose.offsetAndRotation(0f, 20f, 0f, 0f, 0f, 0f));
		PartDefinition head = thorax.addOrReplaceChild("head", CubeListBuilder.create()
				.texOffs(18, 0).addBox(-1.5f, -1.5f, -3f, 3f, 3f, 3f)
				.texOffs(30, 0).addBox(-2f, -2.5f, -2.5f, 1f, 1f, 1f)
				.texOffs(34, 0).addBox(1f, -2.5f, -2.5f, 1f, 1f, 1f)
				.texOffs(38, 0).addBox(-0.5f, -0.5f, -4f, 1f, 1f, 1f), PartPose.offsetAndRotation(0f, 0f, -3f, 0f, 0f, 0f));
		PartDefinition abdomen1 = thorax.addOrReplaceChild("abdomen1", CubeListBuilder.create()
				.texOffs(42, 0).addBox(-1.5f, -1.5f, 0f, 3f, 3f, 3f), PartPose.offsetAndRotation(0f, 0f, 2f, 0.55f, 0f, 0f));
		PartDefinition abdomen2 = abdomen1.addOrReplaceChild("abdomen2", CubeListBuilder.create()
				.texOffs(54, 0).addBox(-1f, -1f, 0f, 2f, 2f, 3f), PartPose.offsetAndRotation(0f, 0f, 3f, -0.9f, 0f, 0f));
		PartDefinition fan = abdomen2.addOrReplaceChild("fan", CubeListBuilder.create()
				.texOffs(0, 9).addBox(-2f, 0f, 0f, 4f, 0f, 3f), PartPose.offsetAndRotation(0f, 0f, 3f, 0.3f, 0f, 0f));
		PartDefinition antL = head.addOrReplaceChild("antL", CubeListBuilder.create()
				.texOffs(14, 9).addBox(-0.5f, -0.5f, -6f, 1f, 1f, 6f), PartPose.offsetAndRotation(0.8f, -1f, -2.5f, 0.35f, 0.35f, 0f));
		PartDefinition antR = head.addOrReplaceChild("antR", CubeListBuilder.create()
				.texOffs(28, 9).addBox(-0.5f, -0.5f, -6f, 1f, 1f, 6f), PartPose.offsetAndRotation(-0.8f, -1f, -2.5f, 0.35f, -0.35f, 0f));
		PartDefinition legL = thorax.addOrReplaceChild("legL", CubeListBuilder.create()
				.texOffs(42, 9).addBox(0f, 0f, -2f, 1f, 3f, 1f)
				.texOffs(46, 9).addBox(0f, 0f, 0f, 1f, 3f, 1f), PartPose.offsetAndRotation(1.5f, 1.5f, 0f, 0f, 0f, -0.2f));
		PartDefinition legR = thorax.addOrReplaceChild("legR", CubeListBuilder.create()
				.texOffs(50, 9).addBox(-1f, 0f, -2f, 1f, 3f, 1f)
				.texOffs(54, 9).addBox(-1f, 0f, 0f, 1f, 3f, 1f), PartPose.offsetAndRotation(-1.5f, 1.5f, 0f, 0f, 0f, 0.2f));
		PartDefinition clawL = head.addOrReplaceChild("clawL", CubeListBuilder.create()
				.texOffs(0, 16).addBox(-0.5f, 0f, -3f, 1f, 1f, 3f)
				.texOffs(8, 16).addBox(-1f, -0.5f, -5f, 2f, 2f, 2f), PartPose.offsetAndRotation(1.2f, 1f, -2.5f, 0f, 0.25f, 0f));
		PartDefinition clawR = head.addOrReplaceChild("clawR", CubeListBuilder.create()
				.texOffs(16, 16).addBox(-0.5f, 0f, -3f, 1f, 1f, 3f)
				.texOffs(24, 16).addBox(-1f, -0.5f, -5f, 2f, 2f, 2f), PartPose.offsetAndRotation(-1.2f, 1f, -2.5f, 0f, -0.25f, 0f));
		return LayerDefinition.create(mesh, 64, 24);
	}

	@Override
	public void setupAnim(BottomRenderState state) {
		super.setupAnim(state);
		float t = state.ageInTicks;
		// Antennae sweep, abdomen waves slowly, legs and claws twitch.
		this.antL.yRot = 0.35f + (float) Math.sin(t * 0.13f) * 0.15f;
		this.antR.yRot = -0.35f - (float) Math.sin(t * 0.13f + 1.3f) * 0.15f;
		this.antL.xRot = 0.35f + (float) Math.sin(t * 0.09f + 0.5f) * 0.08f;
		this.antR.xRot = 0.35f + (float) Math.sin(t * 0.09f + 2.0f) * 0.08f;
		float wave = (float) Math.sin(t * 0.07f);
		this.abdomen1.xRot = 0.55f + wave * 0.12f;
		this.abdomen2.xRot = -0.9f - wave * 0.15f;
		this.fan.xRot = 0.3f + (float) Math.sin(t * 0.21f) * 0.12f;
		this.legL.xRot = (float) Math.sin(t * 0.18f) * 0.15f;
		this.legR.xRot = (float) Math.sin(t * 0.18f + 3.1f) * 0.15f;
		this.clawL.yRot = 0.25f + (float) Math.sin(t * 0.05f + 1f) * 0.1f;
		this.clawR.yRot = -0.25f - (float) Math.sin(t * 0.05f) * 0.1f;
	}
}
