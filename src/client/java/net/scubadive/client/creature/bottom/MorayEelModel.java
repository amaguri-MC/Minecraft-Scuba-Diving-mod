import net.minecraft.client.model.geom.builders.PartDefinition;
import net.scubadive.ScubaDive;

/**
 * Moray eel: head at -z, long jointed body trailing along +z (it lies inside the rock crevice).
 * Texture generated by tools/F3_tex.py.
 */
@SuppressWarnings("unused")
public class MorayEelModel extends EntityModel<BottomRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(ScubaDive.id("moray_eel"), "main");

	private final ModelPart body1;
	private final ModelPart head;
	private final ModelPart jaw;
	private final ModelPart body2;
	private final ModelPart body3;
	private final ModelPart body4;
	private final ModelPart body5;
	private final ModelPart body6;
	private final ModelPart tail;

	public MorayEelModel(ModelPart root) {
		super(root);
		this.body1 = root.getChild("body1");
		this.head = this.body1.getChild("head");
		this.jaw = this.head.getChild("jaw");
		this.body2 = this.body1.getChild("body2");
		this.body3 = this.body2.getChild("body3");
		this.body4 = this.body3.getChild("body4");
		this.body5 = this.body4.getChild("body5");
		this.body6 = this.body5.getChild("body6");
		this.tail = this.body6.getChild("tail");
	}

	public static LayerDefinition createBodyLayer() {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
		PartDefinition body1 = root.addOrReplaceChild("body1", CubeListBuilder.create()
				.texOffs(0, 0).addBox(-3f, -3f, 0f, 6f, 6f, 7f)
				.texOffs(26, 0).addBox(0f, -5f, 0f, 0f, 2f, 7f), PartPose.offsetAndRotation(0f, 16f, 0f, 0f, 0f, 0f));
		PartDefinition head = body1.addOrReplaceChild("head", CubeListBuilder.create()
				.texOffs(0, 13).addBox(-3f, -3f, -8f, 6f, 5f, 8f)
				.texOffs(28, 13).addBox(-2f, -1.5f, -11f, 4f, 3f, 3f)
				.texOffs(42, 13).addBox(-1.5f, -2.5f, -10f, 1f, 1f, 1f)
				.texOffs(46, 13).addBox(0.5f, -2.5f, -10f, 1f, 1f, 1f)
				.texOffs(50, 13).addBox(-3.5f, -2f, -6f, 1f, 2f, 2f)
				.texOffs(56, 13).addBox(2.5f, -2f, -6f, 1f, 2f, 2f), PartPose.offsetAndRotation(0f, 0f, 0f, 0f, 0f, 0f));
		PartDefinition jaw = head.addOrReplaceChild("jaw", CubeListBuilder.create()
				.texOffs(0, 26).addBox(-2.5f, 0f, -9f, 5f, 2f, 9f), PartPose.offsetAndRotation(0f, 2f, -1f, 0.15f, 0f, 0f));
		PartDefinition body2 = body1.addOrReplaceChild("body2", CubeListBuilder.create()
				.texOffs(28, 26).addBox(-3f, -3f, 0f, 6f, 6f, 7f)
				.texOffs(0, 39).addBox(0f, -5f, 0f, 0f, 2f, 7f), PartPose.offsetAndRotation(0f, 0f, 7f, 0f, 0f, 0f));
		PartDefinition body3 = body2.addOrReplaceChild("body3", CubeListBuilder.create()
				.texOffs(14, 39).addBox(-2.5f, -3f, 0f, 5f, 6f, 7f)
				.texOffs(38, 39).addBox(0f, -5f, 0f, 0f, 2f, 7f), PartPose.offsetAndRotation(0f, 0f, 7f, 0f, 0f, 0f));
		PartDefinition body4 = body3.addOrReplaceChild("body4", CubeListBuilder.create()
				.texOffs(0, 52).addBox(-2.5f, -2.5f, 0f, 5f, 5f, 7f)
				.texOffs(24, 52).addBox(0f, -4.5f, 0f, 0f, 2f, 7f), PartPose.offsetAndRotation(0f, 0f, 7f, 0f, 0f, 0f));
		PartDefinition body5 = body4.addOrReplaceChild("body5", CubeListBuilder.create()
				.texOffs(38, 52).addBox(-2f, -2.5f, 0f, 4f, 5f, 7f)
				.texOffs(0, 64).addBox(0f, -4.5f, 0f, 0f, 2f, 7f), PartPose.offsetAndRotation(0f, 0f, 7f, 0f, 0f, 0f));
		PartDefinition body6 = body5.addOrReplaceChild("body6", CubeListBuilder.create()
				.texOffs(14, 64).addBox(-2f, -2f, 0f, 4f, 4f, 7f)
				.texOffs(36, 64).addBox(0f, -4f, 0f, 0f, 2f, 7f), PartPose.offsetAndRotation(0f, 0f, 7f, 0f, 0f, 0f));
		PartDefinition tail = body6.addOrReplaceChild("tail", CubeListBuilder.create()
				.texOffs(0, 75).addBox(-1.5f, -2f, 0f, 3f, 4f, 6f)
				.texOffs(18, 75).addBox(0f, -4f, 0f, 0f, 8f, 6f), PartPose.offsetAndRotation(0f, 0f, 7f, 0f, 0f, 0f));
		return LayerDefinition.create(mesh, 64, 96);
	}

	@Override
	public void setupAnim(BottomRenderState state) {
		super.setupAnim(state);
		float t = state.ageInTicks;
		float open;
		float rate;
		if (state.agitated) {
			// Snapping wide, body tensed and swaying fast.
			open = 0.45f + (float) Math.sin(t * 0.55f) * 0.25f;
			rate = 0.22f;
		} else {
			// Resting: the mouth pumps open and shut slowly.
			open = 0.12f + ((float) Math.sin(t * 0.14f) * 0.5f + 0.5f) * 0.3f;
			rate = 0.07f;
		}
		this.jaw.xRot = open;
		this.head.xRot = -open * 0.2f;
		float amp = state.agitated ? 1.6f : 1.0f;
		this.body1.yRot = (float) Math.sin(t * rate) * 0.03f * amp;
		this.body2.yRot = (float) Math.sin(t * rate - 0.6f) * 0.07f * amp;
		this.body3.yRot = (float) Math.sin(t * rate - 1.2f) * 0.11f * amp;
		this.body4.yRot = (float) Math.sin(t * rate - 1.8f) * 0.15f * amp;
		this.body5.yRot = (float) Math.sin(t * rate - 2.4f) * 0.2f * amp;
		this.body6.yRot = (float) Math.sin(t * rate - 3.0f) * 0.25f * amp;
		this.tail.yRot = (float) Math.sin(t * rate - 3.6f) * 0.3f * amp;
	}
}
