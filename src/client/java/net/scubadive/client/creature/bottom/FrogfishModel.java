package net.scubadive.client.creature.bottom;

import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.scubadive.ScubaDive;

/** Frogfish: lumpy blob with a big mouth, limb-like fins and a fishing lure. Texture generated by tools/F3_tex.py. */
@SuppressWarnings("unused")
public class FrogfishModel extends EntityModel<BottomRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(ScubaDive.id("frogfish"), "main");

	private final ModelPart body;
	private final ModelPart jaw;
	private final ModelPart rod;
	private final ModelPart esca;
	private final ModelPart armL;
	private final ModelPart armR;
	private final ModelPart dorsal;
	private final ModelPart tailFin;

	public FrogfishModel(ModelPart root) {
		super(root);
		this.body = root.getChild("body");
		this.jaw = this.body.getChild("jaw");
		this.rod = this.body.getChild("rod");
		this.esca = this.rod.getChild("esca");
		this.armL = this.body.getChild("armL");
		this.armR = this.body.getChild("armR");
		this.dorsal = this.body.getChild("dorsal");
		this.tailFin = this.body.getChild("tail").getChild("tailFin");
	}

	public static LayerDefinition createBodyLayer() {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
		PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create()
				.texOffs(0, 0).addBox(-4f, -4f, -4f, 8f, 8f, 8f)
				.texOffs(32, 0).addBox(-3.5f, -5f, -3f, 2f, 2f, 2f)
				.texOffs(40, 0).addBox(1.5f, -5f, -3f, 2f, 2f, 2f)
				.texOffs(48, 0).addBox(-2.5f, -4.5f, 0f, 2f, 1f, 2f)
				.texOffs(56, 0).addBox(1f, -4.5f, 2f, 2f, 1f, 2f)
				.texOffs(0, 16).addBox(-4.5f, -1f, 1f, 1f, 2f, 2f)
				.texOffs(6, 16).addBox(3.5f, -2f, -1f, 1f, 2f, 2f)
				.texOffs(12, 16).addBox(-2f, -2f, 3.5f, 3f, 2f, 1f)
				.texOffs(20, 16).addBox(0.5f, -4.5f, -2f, 2f, 1f, 1f)
				.texOffs(26, 16).addBox(-4.5f, 1.5f, -2f, 1f, 1f, 2f), PartPose.offsetAndRotation(0f, 19f, 0f, 0f, 0f, 0f));
		PartDefinition mouth = body.addOrReplaceChild("mouth", CubeListBuilder.create()
				.texOffs(32, 16).addBox(-3f, -1f, -3f, 6f, 3f, 3f), PartPose.offsetAndRotation(0f, 0f, -4f, 0f, 0f, 0f));
		PartDefinition jaw = body.addOrReplaceChild("jaw", CubeListBuilder.create()
				.texOffs(0, 22).addBox(-3f, 0f, -4f, 6f, 2f, 4f), PartPose.offsetAndRotation(0f, 2f, -4f, 0f, 0f, 0f));
		PartDefinition rod = body.addOrReplaceChild("rod", CubeListBuilder.create()
				.texOffs(20, 22).addBox(-0.5f, -5f, -0.5f, 1f, 5f, 1f), PartPose.offsetAndRotation(0f, -4f, -3f, 0.35f, 0f, 0f));
		PartDefinition esca = rod.addOrReplaceChild("esca", CubeListBuilder.create()
				.texOffs(24, 22).addBox(-1f, -2f, -1f, 2f, 2f, 2f), PartPose.offsetAndRotation(0f, -5f, 0f, 0f, 0f, 0f));
		PartDefinition armL = body.addOrReplaceChild("armL", CubeListBuilder.create()
				.texOffs(32, 22).addBox(0f, 0f, -1f, 2f, 4f, 2f), PartPose.offsetAndRotation(4f, 2f, -2f, 0f, 0f, -0.3f));
		PartDefinition armR = body.addOrReplaceChild("armR", CubeListBuilder.create()
				.texOffs(40, 22).addBox(-2f, 0f, -1f, 2f, 4f, 2f), PartPose.offsetAndRotation(-4f, 2f, -2f, 0f, 0f, 0.3f));
		PartDefinition legL = body.addOrReplaceChild("legL", CubeListBuilder.create()
				.texOffs(48, 22).addBox(0f, 0f, -1f, 2f, 2f, 2f), PartPose.offsetAndRotation(3.5f, 2f, 2f, 0f, 0f, -0.2f));
		PartDefinition legR = body.addOrReplaceChild("legR", CubeListBuilder.create()
				.texOffs(56, 22).addBox(-2f, 0f, -1f, 2f, 2f, 2f), PartPose.offsetAndRotation(-3.5f, 2f, 2f, 0f, 0f, 0.2f));
		PartDefinition dorsal = body.addOrReplaceChild("dorsal", CubeListBuilder.create()
				.texOffs(0, 28).addBox(0f, -2f, 0f, 0f, 2f, 5f), PartPose.offsetAndRotation(0f, -4f, 0f, 0f, 0f, 0f));
		PartDefinition tail = body.addOrReplaceChild("tail", CubeListBuilder.create()
				.texOffs(10, 28).addBox(-1.5f, -2f, 0f, 3f, 4f, 2f), PartPose.offsetAndRotation(0f, 1f, 4f, 0f, 0f, 0f));
		PartDefinition tailFin = tail.addOrReplaceChild("tailFin", CubeListBuilder.create()
				.texOffs(20, 28).addBox(0f, -2f, 0f, 0f, 4f, 3f), PartPose.offsetAndRotation(0f, 0f, 2f, 0f, 0f, 0f));
		return LayerDefinition.create(mesh, 64, 40);
	}

	@Override
	public void setupAnim(BottomRenderState state) {
		super.setupAnim(state);
		float t = state.ageInTicks;
		// Lure dangles and twitches; now and then the huge mouth gapes. Otherwise it sits still.
		this.rod.xRot = 0.35f + (float) Math.sin(t * 0.11f) * 0.18f;
		this.rod.zRot = (float) Math.sin(t * 0.07f + 1f) * 0.1f;
		this.esca.xRot = (float) Math.sin(t * 0.23f) * 0.35f;
		float yawn = (float) Math.sin(t * 0.021f);
		this.jaw.xRot = yawn > 0.96f ? (yawn - 0.96f) / 0.04f * 0.5f : 0.0f;
		this.armL.zRot = -0.3f + (float) Math.sin(t * 0.04f) * 0.03f;
		this.armR.zRot = 0.3f - (float) Math.sin(t * 0.04f + 1f) * 0.03f;
		this.dorsal.zRot = (float) Math.sin(t * 0.1f) * 0.05f;
		this.tailFin.yRot = (float) Math.sin(t * 0.06f) * 0.1f;
	}
}
