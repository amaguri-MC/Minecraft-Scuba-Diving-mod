package net.scubadive.client.creature.bottom;

import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.scubadive.ScubaDive;

/** Clownfish: stocky orange body, three white bands, fan tail. Texture generated by tools/F3_tex.py. */
@SuppressWarnings("unused")
public class ClownfishModel extends EntityModel<BottomRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(ScubaDive.id("clownfish"), "main");

	private final ModelPart body;
	private final ModelPart head;
	private final ModelPart stalk;
	private final ModelPart tail;
	private final ModelPart dorsal;
	private final ModelPart pecL;
	private final ModelPart pecR;

	public ClownfishModel(ModelPart root) {
		super(root);
		this.body = root.getChild("body");
		this.head = this.body.getChild("head");
		this.stalk = this.body.getChild("stalk");
		this.tail = this.stalk.getChild("tail");
		this.dorsal = this.body.getChild("dorsal");
		this.pecL = this.body.getChild("pecL");
		this.pecR = this.body.getChild("pecR");
	}

	public static LayerDefinition createBodyLayer() {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
		PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create()
				.texOffs(0, 0).addBox(-2.5f, -3.5f, -5f, 5f, 7f, 10f), PartPose.offsetAndRotation(0f, 20f, 0f, 0f, 0f, 0f));
		PartDefinition head = body.addOrReplaceChild("head", CubeListBuilder.create()
				.texOffs(30, 0).addBox(-2f, -3f, -3f, 4f, 6f, 3f), PartPose.offsetAndRotation(0f, 0f, -5f, 0f, 0f, 0f));
		PartDefinition stalk = body.addOrReplaceChild("stalk", CubeListBuilder.create()
				.texOffs(44, 0).addBox(-1f, -2f, 0f, 2f, 4f, 2f), PartPose.offsetAndRotation(0f, 0f, 5f, 0f, 0f, 0f));
		PartDefinition tail = stalk.addOrReplaceChild("tail", CubeListBuilder.create()
				.texOffs(52, 0).addBox(0f, -3f, 0f, 0f, 6f, 3f), PartPose.offsetAndRotation(0f, 0f, 2f, 0f, 0f, 0f));
		PartDefinition dorsal = body.addOrReplaceChild("dorsal", CubeListBuilder.create()
				.texOffs(0, 17).addBox(0f, -3f, 0f, 0f, 3f, 6f), PartPose.offsetAndRotation(0f, -3.5f, -1f, 0f, 0f, 0f));
		PartDefinition pecL = body.addOrReplaceChild("pecL", CubeListBuilder.create()
				.texOffs(12, 17).addBox(0f, 0f, 0f, 3f, 0f, 2f), PartPose.offsetAndRotation(2.5f, 1.5f, -2f, 0f, 0f, 0.25f));
		PartDefinition pecR = body.addOrReplaceChild("pecR", CubeListBuilder.create()
				.texOffs(22, 17).addBox(-3f, 0f, 0f, 3f, 0f, 2f), PartPose.offsetAndRotation(-2.5f, 1.5f, -2f, 0f, 0f, -0.25f));
		PartDefinition anal = body.addOrReplaceChild("anal", CubeListBuilder.create()
				.texOffs(32, 17).addBox(0f, 0f, 0f, 0f, 2f, 3f), PartPose.offsetAndRotation(0f, 3.5f, 2f, 0f, 0f, 0f));
		return LayerDefinition.create(mesh, 64, 32);
	}

	@Override
	public void setupAnim(BottomRenderState state) {
		super.setupAnim(state);
		float t = state.ageInTicks;
		float beat = t * 0.45f;
		this.body.yRot = (float) Math.sin(beat + 1.0f) * 0.05f;
		this.stalk.yRot = (float) Math.sin(beat - 0.4f) * 0.22f;
		this.tail.yRot = (float) Math.sin(beat - 0.9f) * 0.4f;
		this.head.yRot = (float) Math.sin(beat + 1.5f) * 0.04f;
		this.dorsal.zRot = (float) Math.sin(t * 0.12f) * 0.04f;
		float flap = (float) Math.sin(t * 0.35f) * 0.3f;
		this.pecL.zRot = 0.3f + flap;
		this.pecR.zRot = -0.3f - flap;
	}
}
