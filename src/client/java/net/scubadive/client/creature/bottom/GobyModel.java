package net.scubadive.client.creature.bottom;

import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.scubadive.ScubaDive;

/** Sand goby: slim sand-coloured body, blunt head with eyes on top, two dorsal fins. Texture generated by tools/F3_tex.py. */
@SuppressWarnings("unused")
public class GobyModel extends EntityModel<BottomRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(ScubaDive.id("goby"), "main");

	private final ModelPart body;
	private final ModelPart head;
	private final ModelPart stalk;
	private final ModelPart tail;
	private final ModelPart dorsal1;
	private final ModelPart dorsal2;
	private final ModelPart pecL;
	private final ModelPart pecR;

	public GobyModel(ModelPart root) {
		super(root);
		this.body = root.getChild("body");
		this.head = this.body.getChild("head");
		this.stalk = this.body.getChild("stalk");
		this.tail = this.stalk.getChild("tail");
		this.dorsal1 = this.body.getChild("dorsal1");
		this.dorsal2 = this.body.getChild("dorsal2");
		this.pecL = this.body.getChild("pecL");
		this.pecR = this.body.getChild("pecR");
	}

	public static LayerDefinition createBodyLayer() {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
		PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create()
				.texOffs(0, 0).addBox(-1.5f, -2f, -3f, 3f, 4f, 7f), PartPose.offsetAndRotation(0f, 21f, 0f, 0f, 0f, 0f));
		PartDefinition head = body.addOrReplaceChild("head", CubeListBuilder.create()
				.texOffs(20, 0).addBox(-2f, -2f, -3f, 4f, 4f, 3f)
				.texOffs(34, 0).addBox(-1.5f, -3f, -2f, 1f, 1f, 1f)
				.texOffs(38, 0).addBox(0.5f, -3f, -2f, 1f, 1f, 1f), PartPose.offsetAndRotation(0f, 0f, -3f, 0f, 0f, 0f));
		PartDefinition stalk = body.addOrReplaceChild("stalk", CubeListBuilder.create()
				.texOffs(42, 0).addBox(-1f, -1.5f, 0f, 2f, 3f, 2f), PartPose.offsetAndRotation(0f, 0f, 4f, 0f, 0f, 0f));
		PartDefinition tail = stalk.addOrReplaceChild("tail", CubeListBuilder.create()
				.texOffs(50, 0).addBox(0f, -2f, 0f, 0f, 4f, 3f), PartPose.offsetAndRotation(0f, 0f, 2f, 0f, 0f, 0f));
		PartDefinition dorsal1 = body.addOrReplaceChild("dorsal1", CubeListBuilder.create()
				.texOffs(56, 0).addBox(0f, -2f, 0f, 0f, 2f, 3f), PartPose.offsetAndRotation(0f, -2f, -2f, 0f, 0f, 0f));
		PartDefinition dorsal2 = body.addOrReplaceChild("dorsal2", CubeListBuilder.create()
				.texOffs(0, 11).addBox(0f, -3f, 0f, 0f, 3f, 3f), PartPose.offsetAndRotation(0f, -2f, 1.5f, 0f, 0f, 0f));
		PartDefinition pecL = body.addOrReplaceChild("pecL", CubeListBuilder.create()
				.texOffs(6, 11).addBox(0f, -1f, 0f, 0f, 3f, 3f), PartPose.offsetAndRotation(1.5f, 0.5f, -2.5f, 0f, 0.5f, 0f));
		PartDefinition pecR = body.addOrReplaceChild("pecR", CubeListBuilder.create()
				.texOffs(12, 11).addBox(0f, -1f, 0f, 0f, 3f, 3f), PartPose.offsetAndRotation(-1.5f, 0.5f, -2.5f, 0f, -0.5f, 0f));
		PartDefinition pelvic = body.addOrReplaceChild("pelvic", CubeListBuilder.create()
				.texOffs(18, 11).addBox(-1.5f, 0f, 0f, 3f, 1f, 3f), PartPose.offsetAndRotation(0f, 2f, -2f, 0f, 0f, 0f));
		PartDefinition anal = body.addOrReplaceChild("anal", CubeListBuilder.create()
				.texOffs(30, 11).addBox(0f, 0f, 0f, 0f, 2f, 3f), PartPose.offsetAndRotation(0f, 2f, 1.5f, 0f, 0f, 0f));
		return LayerDefinition.create(mesh, 64, 24);
	}

	@Override
	public void setupAnim(BottomRenderState state) {
		super.setupAnim(state);
		float t = state.ageInTicks;
		// Resting goby: gill-pumping body, lazily fluttering fins.
		this.body.xRot = (float) Math.sin(t * 0.2f) * 0.015f;
		this.tail.yRot = (float) Math.sin(t * 0.08f) * 0.12f;
		this.stalk.yRot = (float) Math.sin(t * 0.08f - 0.5f) * 0.06f;
		this.head.yRot = (float) Math.sin(t * 0.03f) * 0.18f;
		this.dorsal1.zRot = (float) Math.sin(t * 0.17f) * 0.05f;
		this.dorsal2.zRot = (float) Math.sin(t * 0.17f + 0.8f) * 0.05f;
		float flap = (float) Math.sin(t * 0.3f) * 0.18f;
		this.pecL.yRot = 0.5f + flap;
		this.pecR.yRot = -0.5f - flap;
	}
}
