	@Override
	public void setupAnim(PenguinRenderState state) {
		super.setupAnim(state);
		this.resetPose();
		float t = state.ageInTicks + state.phase;
		float swim = state.swimAmount;
		boolean swimming = swim > 0.5f;
		float land = 1.0f - swim;

		this.flipperL.visible = !swimming;
		this.flipperR.visible = !swimming;
		this.footL.visible = !swimming;
		this.footR.visible = !swimming;
		this.swimFlipperL.visible = swimming;
		this.swimFlipperR.visible = swimming;
		this.swimFootL.visible = swimming;
		this.swimFootR.visible = swimming;

		// Land: waddle. The whole bird rocks side to side on its feet, flippers held a little open.
		float walk = Math.min(1.0f, state.walkAnimationSpeed * 2.5f) * land;
		float step = state.walkAnimationPos * 0.9f;
		this.base.zRot = Mth.sin(step) * 0.16f * walk;
		this.footL.xRot = Mth.sin(step) * 0.5f * walk;
		this.footR.xRot = -Mth.sin(step) * 0.5f * walk;
		float open = 0.35f * walk + 0.03f * Mth.sin(t * 0.05f);
		this.flipperL.zRot -= open;
		this.flipperR.zRot += open;

		// Water: tip forward to horizontal and follow the swimming pitch.
		this.body.xRot = swim * (Mth.HALF_PI + state.xRot * Mth.DEG_TO_RAD);
		float beat = Mth.sin(t * 0.55f) * (0.25f + 0.45f * Math.min(1.0f, state.walkAnimationSpeed * 3.0f));
		this.swimFlipperL.zRot += beat;
		this.swimFlipperR.zRot -= beat;
		this.swimFootL.xRot = Mth.sin(t * 0.55f + 1.0f) * 0.15f;
		this.swimFootR.xRot = Mth.sin(t * 0.55f + 2.0f) * 0.15f;

		if (swimming) {
			// Head turned to look along the swimming direction (beak forward, in line with the body).
			this.head.xRot = -Mth.HALF_PI * swim;
		} else {
			// Dozing: the head follows the look target, now and then a quick head shake and a sleepy tilt.
			this.head.yRot = state.yRot * Mth.DEG_TO_RAD;
			this.head.xRot = state.xRot * Mth.DEG_TO_RAD * 0.6f;
			float cycle = (t % 260.0f);
			if (cycle < 16.0f) {
				this.head.yRot += Mth.sin(cycle * 1.7f) * 0.55f * (1.0f - cycle / 16.0f);
			}
			this.head.zRot = Mth.sin(t * 0.021f) * 0.09f;
		}
	}

